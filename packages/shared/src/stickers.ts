// Stickers and GIF search.
//
// A sticker is an image sent as a message of its own: Message.sticker_items holds a frozen copy of each
// sticker ({ id, name, format, url }) so it keeps rendering after the sticker is renamed. Two sources:
//   - the built-in "Huddle Buddies" pack below (SVGs served by the web app from /stickers/), and
//   - per-server stickers uploaded by members with MANAGE_EMOJIS ("Manage Expressions"), usable in that
//     server only, managed under Server Settings → Stickers.
// Send one with POST /channels/:id/messages { sticker_ids: [id] } (content optional).

export type StickerFormat = 'png' | 'apng' | 'gif' | 'webp' | 'svg';

export interface StickerItem {
  id: string; // snowflake for server stickers, "hb_<slug>" for built-ins
  name: string;
  format: StickerFormat;
  url: string;
}

export interface GuildSticker extends StickerItem {
  guild_id: string;
  description: string | null;
  /** The related emoji (a unicode emoji), used for search. */
  tags: string;
  creator_id: string | null;
  created_at: string;
}

export interface BuiltinSticker extends StickerItem {
  description: string;
  tags: string;
  category: BuiltinStickerCategory;
  /** Animated SVG; `still` is a static frame for reduced-motion viewers. */
  animated: boolean;
  still: string | null;
}

