export const stickerItem = (s: StickerItem): StickerItem => ({ id: s.id, name: s.name, format: s.format, url: s.url });

/** Text stand-in for previews, notifications and search results. */
export const stickerLabel = (s: { name: string }): string => `[sticker] ${s.name}`;

// ---- GIF search (GET /gifs/search?q=&offset=, GET /gifs/trending?offset=) ----

/** GET /config — server capabilities the client checks before showing optional UI. */
export interface ClientConfig {
  /** GIF search is available (a provider key is configured on the server). */
  gifs: boolean;
  /** Provider name for attribution, e.g. "GIPHY". */
  gif_provider: string | null;
}

export interface GifResult {
  id: string;
  title: string;
  /** What gets sent: a direct media URL on the provider's domain (renders as an inline GIF embed). */
  url: string;
  /** Smaller animated preview for the picker grid. */
  preview: string;
  width: number;
  height: number;
}

export interface GifSearchResponse {
  results: GifResult[];
  /** Offset for the next page, or null at the end. */
  next: number | null;
}
